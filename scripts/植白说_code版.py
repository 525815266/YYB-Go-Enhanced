def api_url(api_path: str) -> str:
    return API_BASE + api_path.lstrip("/")


class AccountSession:
    """单个 code 服务地址的会话: token（X-Dts-Token 头）+ userId"""

    def __init__(self, server: str):
        self.server = server
        self.token = ""
        self.user_info: Dict[str, Any] = {}

    @property
    def user_id(self) -> Any:
        return self.user_info.get("userId") or self.user_info.get("id") or 1

    def request(self, server_unused: str, method: str, api_path: str, data: Dict[str, Any] | None = None,
                auth: bool = True, proxies: Dict[str, str] | None = None) -> Dict[str, Any]:
        url = api_url(api_path)
        headers = common_headers(self.token if auth else None)
        kwargs: Dict[str, Any] = {"headers": headers, "timeout": REQUEST_TIMEOUT}
        if proxies:
            kwargs["proxies"] = proxies
        if method.upper() == "GET":
            kwargs["params"] = data or {}
        else:
            kwargs["json"] = data or {}
        try:
            response = requests.request(method, url, **kwargs)
        except Exception:
            if not proxies or not ENABLE_DIRECT_FALLBACK:
                raise
            kwargs.pop("proxies", None)
            response = requests.request(method, url, **kwargs)
        try:
            result = response.json()
        except Exception:
            raise RuntimeError(f"HTTP {response.status_code}: {response.text[:200]}")
        if response.status_code != 200:
            raise RuntimeError(f"HTTP {response.status_code}: {json_preview(result, 200)}")
        if int(result.get("errno") or 0) != 0:
            raise RuntimeError(f"{result.get('errno') or ''} {result.get('errmsg') or result.get('message') or json_preview(result, 150)}".strip())
        return result

    def set_cached_token(self) -> None:
        cache = load_token_cache()
        cache[self.server] = {"token": self.token, "userInfo": self.user_info, "updateTime": datetime.now().isoformat()}
        save_token_cache(cache)

    def login(self, proxies: Dict[str, str] | None) -> None:
        code = get_code(self.server)
        if not code:
            raise RuntimeError("code 服务未返回 code")

        print("🔐 [登录] 使用 code 换 token")
        result = self.request(self.server, "POST", "auth/login_by_weixin",
                              {"code": code, "userInfo": {}, "shareUserId": 1}, auth=False, proxies=proxies)
        token = (safe_data(result) or {}).get("token") or ""
        if not token:
            raise RuntimeError(f"登录响应未返回token: {json_preview(result, 200)}")
        self.token = token
        self.user_info = safe_data(result).get("userInfo") or {}
        self.set_cached_token()
        nickname = self.user_info.get("nickname") or ""
        print(f"✅ [登录] 登录成功: {nickname or 'userId=' + str(self.user_id)}")

    def ensure_login(self, proxies: Dict[str, str] | None) -> None:
        cached = load_token_cache().get(self.server) or {}
        if cached.get("token"):
            self.token = cached["token"]
            self.user_info = cached.get("userInfo") or {}
            try:
                self.request(self.server, "GET", "user/getUserIntegral", {"userId": self.user_id},
                             proxies=proxies)
                print("✅ [缓存] 使用缓存token")
                return
            except Exception:
                print("⚠️ [缓存] 缓存token失效，重新登录")
                self.token = ""
        self.login(proxies)

    def points(self, proxies: Dict[str, str] | None, prefix: str = "当前") -> str:
        try:
            result = self.request(self.server, "GET", "user/getUserIntegral", {"userId": self.user_id}, proxies=proxies)
            value = (safe_data(result) or {}).get("integral")
            print(f"💰 [积分] {prefix}积分: {value if value is not None else '-'}")
            return str(value if value is not None else "-")
        except Exception:
            return "-"

    def sign(self, proxies: Dict[str, str] | None) -> str:
        status = self.request(self.server, "GET", "home/signDay", {"userId": self.user_id}, proxies=proxies)
        if (safe_data(status) or {}).get("isSign"):
            print("✅ [签到] 今日已签到")
            return "今日已签到"
        self.request(self.server, "GET", "home/sign", {"userId": self.user_id}, proxies=proxies)
        print("✅ [签到] 签到成功")
        return "签到成功"

    def run_flow(self, proxies: Dict[str, str] | None) -> Dict[str, Any]:
        sign_msg = self.sign(proxies)
        points = self.points(proxies, "签到后")
        return {"signMsg": sign_msg, "pointsMsg": points}


