# ====================== Token缓存管理 ======================
def load_token_cache() -> Dict[str, Any]:
    try:
        if os.path.exists(COOKIE_FILE):
            with open(COOKIE_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
    except Exception as exc:
        print(f"⚠️ [缓存] 读取失败: {exc}")
    return {}


def save_token_cache(cache: Dict[str, Any]) -> None:
    try:
        with open(COOKIE_FILE, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False, indent=2)
        print("✅ [缓存] Token保存成功")
    except Exception as exc:
        print(f"❌ [缓存] 保存失败: {exc}")


def get_cached_token(server: str) -> str | None:
    cache = load_token_cache()
    data = cache.get(server)
    if data and data.get("token") and data.get("expireTime"):
        try:
            expire = datetime.fromisoformat(data["expireTime"]).timestamp() * 1000
            if time.time() * 1000 < expire - 3600 * 1000:
                print(f"✅ [缓存] 使用 {server} token")
                return data["token"]
        except Exception as exc:
            print(f"⚠️ [缓存] 过期时间解析异常: {exc}")
    return None


def set_cached_token(server: str, token: str, expire_time: str) -> None:
    cache = load_token_cache()
    cache[server] = {"token": token, "expireTime": expire_time, "updateTime": datetime.now().isoformat()}
    save_token_cache(cache)


def login_with_cache(server: str, proxies: Dict[str, str] | None) -> Tuple[str | None, Dict[str, Any] | None]:
    """优先使用缓存 token（金币收益接口验证），失效自动 code 刷新；双 appid 逐个尝试"""
    cache_token = get_cached_token(server)
    if cache_token:
        print("🔍 [缓存] 验证 token")
        try:
            index_resp = api_get(server, AD_INDEX_URL, cache_token, proxies)
            if index_resp.get("code") == 200:
                print("✅ [缓存] token 有效")
                return cache_token, None
        except Exception as exc:
            print(f"⚠️ [缓存] 验证异常: {exc}")
        print("⚠️ [缓存] token 已失效，重新登录")

    raw_login: Dict[str, Any] | None = None
    for appid in APPID:
        code = get_code(server, appid)
        if not code:
            continue

        token, raw_login = login_by_code(server, code, appid, proxies)
        if token:
            expire_time = None
            if raw_login and isinstance(raw_login, dict):
                inner = raw_login.get("data")
                if isinstance(inner, dict):
                    expire_time = inner.get("expireTime") or inner.get("expire_time")
                    expires_in = inner.get("expiresIn")
                    if not expire_time and isinstance(expires_in, (int, float)) and expires_in > 0:
                        expire_time = datetime.fromtimestamp(time.time() + expires_in).isoformat()
            if not expire_time:
                expire_time = datetime.fromtimestamp(time.time() + 24 * 3600).isoformat()
            elif not isinstance(expire_time, str):
                expire_time = datetime.fromtimestamp(expire_time / 1000).isoformat()
            set_cached_token(server, token, expire_time)
            return token, raw_login

    return None, raw_login


def watch_ad(server: str, token: str, proxies: Dict[str, str] | None) -> Tuple[bool, bool]:
    """照源脚本 watchad：提交观看记录。返回 (是否成功, 当日任务是否完成)"""
