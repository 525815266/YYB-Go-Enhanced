    result["server"] = server

    log_account_header(index, total, server)

    proxies, proxy_ip = get_valid_proxy(server)
    result["proxyStatus"] = "使用专属代理" if proxies else "使用直连"
    result["proxyIp"] = proxy_ip or "-"

    sleep(PROXY_FETCH_INTERVAL)

    delay = random.randint(2, 6)
    print(f"⏳ [延迟] 启动延迟 {delay}s")
    sleep(delay)

    session = AccountSession(server)

    try:
        session.ensure_login(proxies)
        result["token"] = mask(session.token)
        result["nickname"] = session.nickname or "-"

        result["pointsMsg"] = session.query_points(proxies)
        result["signMsg"] = session.sign(proxies)
        result["success"] = "签到成功" in result["signMsg"] or "已签到" in result["signMsg"]
        return result

    except RuntimeError as exc:
        if str(exc).startswith("NO_ACCOUNT"):
            result["error"] = f"该微信号还没在玛氏宠享会注册/绑定（{str(exc)[10:]}），先在小程序里登录一次再跑"
            print(f"⚠️ [账号] {result['error']}")
            return result
        result["error"] = traceback.format_exc().strip()
        print(f"❌ [账号] 执行失败: {exc}")
        return result
    except Exception as exc:
        result["error"] = traceback.format_exc().strip()
        print(f"❌ [账号] 执行失败: {exc}")
        return result
