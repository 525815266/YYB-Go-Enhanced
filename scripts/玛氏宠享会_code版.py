# ====================== Token缓存管理 ======================
def load_token_cache() -> Dict[str, Any]:
    try:
        if os.path.exists(COOKIE_FILE):
            with open(COOKIE_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
    except Exception as exc:
        print(f"⚠️ [缓存] 读取失败: {exc}")
    return {}


def save_token_cache(cache: Dict[str, Any]) -> None:
    try:
        with open(COOKIE_FILE, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False, indent=2)
        print("✅ [缓存] Token保存成功")
    except Exception as exc:
        print(f"❌ [缓存] 保存失败: {exc}")



def sign_params(params: Dict[str, Any]) -> Dict[str, Any]:
    """全部业务参数按 key 升序拼 k=v&...，末尾接 salt，MD5 => signature（不参与签名串）"""
    base = "&".join(f"{k}={params[k]}" for k in sorted(params.keys()))
    signature = hashlib.md5((base + SIGN_SALT).encode("utf-8")).hexdigest()
    return {**params, "signature": signature}


def form_encode(payload: Dict[str, Any]) -> str:
    return "&".join(f"{k}={quote(str(v), safe='')}" for k, v in payload.items())


def code_of(resp: Dict[str, Any]) -> "int | float":
    for key in ("code", "errno", "status", "ret", "resultCode"):
        if resp.get(key) is not None:
            return int(resp[key])
    return float("nan")


def msg_of(resp: Dict[str, Any]) -> str:
    return resp.get("msg") or resp.get("message") or resp.get("errmsg") or resp.get("info") or ""


class AccountSession:
    """单个 code 服务地址的会话: access_token + nickname"""

    def __init__(self, server: str):
        self.server = server
        self.token = ""
        self.nickname = ""

    def base_params(self, extra: Dict[str, Any] | None = None) -> Dict[str, Any]:
        return {
            "store_id": STORE_ID, "access_token": self.token,
            "timestamp": int(time.time()), "_version": VERSION, "_platform": PLATFORM,
            **(extra or {}),
        }

    def api_get(self, biz_params: Dict[str, Any], proxies: Dict[str, str] | None) -> Dict[str, Any]:
        signed = sign_params(biz_params)
        response = request_with_proxy(
            "GET", API_URL, params=signed,
            headers={"User-Agent": USER_AGENT, "authority": "petcare-consumer.marschina.com",
                     "Accept": "application/json, text/plain, */*"},
            proxies=proxies, server=self.server,
        )
        try:
            return response.json()
        except Exception:
            return {"code": -1, "msg": f"JSON解析失败: {response.text[:300]}"}

    def login(self, proxies: Dict[str, str] | None) -> None:
        code = get_code(self.server)
        if not code:
            raise RuntimeError("code 服务未返回 code")

        print("🔐 [登录] 使用 code 换 access_token")
        signed = sign_params({
            "store_id": STORE_ID, "r": "api/passport/login",
            "code": code, "type": "p", "login_first": "1", "channel": "default",
            "timestamp": int(time.time()), "_version": VERSION, "_platform": PLATFORM,
        })
        response = request_with_proxy(
            "POST", API_URL, params=signed, data=form_encode(signed),
            headers={"User-Agent": USER_AGENT, "authority": "petcare-consumer.marschina.com",
                     "Content-Type": "application/x-www-form-urlencoded",
                     "Accept": "application/json, text/plain, */*"},
            proxies=proxies, server=self.server,
        )
        try:
            body = response.json()
        except Exception:
            body = {"code": -1, "msg": f"JSON解析失败: {response.text[:300]}"}

        if code_of(body) == 0 and safe_data(body).get("access_token"):
            self.token = str(safe_data(body)["access_token"])
            self.nickname = safe_data(body).get("nickname") or ""
            cache = load_token_cache()
            cache[self.server] = {"token": self.token, "nickname": self.nickname, "updateTime": datetime.now().isoformat()}
            save_token_cache(cache)
            print(f"✅ [登录] 登录成功{f'（{self.nickname}）' if self.nickname else ''}")
            return

        msg = msg_of(body) or json_preview(body, 200)
        if __import__("re").search(r"未注册|不存在|未绑定|请先|注册|激活", str(msg)):
            raise RuntimeError(f"NO_ACCOUNT:{msg}")
        raise RuntimeError(f"登录未返回 access_token: {msg}")

    def ensure_login(self, proxies: Dict[str, str] | None) -> None:
        cached = load_token_cache().get(self.server) or {}
        if cached.get("token"):
            self.token = cached["token"]
            self.nickname = cached.get("nickname", "")
            print("✅ [缓存] 使用缓存token")
            return
        self.login(proxies)

    def query_points(self, proxies: Dict[str, str] | None) -> str:
        try:
            res = self.api_get(self.base_params({"r": "api/user/member", "type": "p"}), proxies)
            if code_of(res) == 0 and isinstance(safe_data(res).get("user_info"), dict):
                integral = safe_data(res)["user_info"].get("integral")
                print(f"💰 [积分] 当前积分: {integral}")
                return str(integral)
        except Exception:
            pass
        return "-"

    def sign(self, proxies: Dict[str, str] | None, retry: bool = True) -> str:
        res = self.api_get(self.base_params({"r": "api/integralmall/integralmall/register", "type": 1}), proxies)
        if code_of(res) == 0:
            got = safe_data(res).get("integral")
            msg = f"签到成功{f'，获得 {got} 积分' if got is not None else ''}"
            print(f"✅ [签到] {msg}")
            return msg
        msg = msg_of(res) or json_preview(res, 200)
        if __import__("re").search(r"已签|签过|签到过|重复|已完成|明天|已经", str(msg)):
            print(f"✅ [签到] 今日已签到（{msg}）")
            return f"今日已签到（{msg}）"
        if retry and __import__("re").search(r"token|登录|未授权|失效|过期|未登录|鉴权|重新登录", str(msg), __import__("re").IGNORECASE):
            print("⚠️ [签到] 会话失效，重新登录后重试")
            cache = load_token_cache()
            cache.pop(self.server, None)
            save_token_cache(cache)
            self.token = ""
            self.login(proxies)
            return self.sign(proxies, retry=False)
        if __import__("re").search(r"请先授权|请授权|未注册|未绑定|绑定手机|完善.*信息|注册会员", str(msg)):
            msg = f"该微信号还没在玛氏宠享会授权/注册会员（{msg}），先在小程序里授权登录一次再跑"
            print(f"⚠️ [签到] {msg}")
            return msg
        print(f"❌ [签到] 签到失败: {msg}")
        return f"签到失败: {msg}"


