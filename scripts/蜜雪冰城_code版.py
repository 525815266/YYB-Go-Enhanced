def get_rsa_key():
    global PRIVATE_KEY
    if PRIVATE_KEY is None:
        try:
            PRIVATE_KEY = serialization.load_pem_private_key(
                PRIVATE_KEY_STR.encode("utf-8"), password=None
            )
        except Exception:
            PRIVATE_KEY = False
    if PRIVATE_KEY is False:
        return None
    return PRIVATE_KEY


def sha256_with_rsa(content: str) -> str | None:
    """RSA-SHA256 签名，base64 后做 URL 变体替换（照源脚本）。"""
    key = get_rsa_key()
    if key is None:
        print("❌ [签名] cryptography 未安装或私钥解析失败，请 pip install cryptography")
        return None
    try:
        signature = key.sign(
            content.encode("utf-8"),
            padding.PKCS1v15(),
            hashes.SHA256(),
        )
        return base64.b64encode(signature).decode("utf-8").replace("/", "_").replace("+", "-")
    except Exception as exc:
        print(f"❌ [签名] 签名异常: {exc}")
        return None


def ts13() -> str:
    return str(int(time.time() * 1000))


def signed_params(extra: Dict[str, Any] | None = None) -> Dict[str, Any]:
    """GET 场景签名参数：appId + t + sign（照源脚本拼串规则）。"""
    t = ts13()
    content = f"appId={APP_ID}&t={t}"
    params: Dict[str, Any] = {"appId": APP_ID, "t": t}
    if extra:
        params.update(extra)
    sign = sha256_with_rsa(content)
    params["sign"] = sign or ""
    return params


def get_signed_body(params: Dict[str, Any] | None = None) -> Dict[str, Any]:
    """POST 场景签名体：appId/t 入体，键排序拼串签名（照源脚本）。"""
    body = dict(params or {})
    body["t"] = int(time.time() * 1000)
    body["appId"] = APP_ID
    content = "&".join(
        f"{key}={json.dumps(body[key], ensure_ascii=False) if isinstance(body[key], (dict, list)) else body[key]}"
        for key in sorted(body.keys())
        if body[key] or body[key] == 0
    )
    body["sign"] = sha256_with_rsa(content) or ""
    return body


