// Official-account (H5) web OAuth code support. A web script needs the code a
// WeChat authorization page appends to the business redirect_uri, not a
// wx.login code: asking wx.login for a non-mini-program AppID returns no code
// and the upstream then refuses the account's OAuth layer within seconds
// (docs/website-appid-getcode-20261103.md). The isolated audit of 2026-10-31
// (docs/h5-legacy-session-compare-20261031.md) verified that the existing YYB
// session carries the /cgi-bin/mmbiz-bin/oauth_authorize CGI (command 1254)
// and returns the redirect with a code that matches the requested callback and
// state. This file wires that verified path into the pool; the A8Key 5112
// route stays an audit-only compatibility path.

const (
	h5OAuthCmdID = 1254
	// Depth limit mirrors the audit harness: OAuth replies nest the callback
	// payload a few protobuf layers deep; anything deeper is malformed.
	h5OAuthMaxDepth = 8
)

var h5OAuthURL = []byte("/cgi-bin/mmbiz-bin/oauth_authorize")

// ErrH5OAuthBusinessRejected reports an explicit non-zero business status from
// the oauth_authorize CGI. It is not a credential failure: the account layer
// must neither mark the account expired nor replay the request after a forced
// refresh, because each confirmation can issue a one-time code.
type ErrH5OAuthBusinessRejected struct {
	Ret int32
}

func (e *ErrH5OAuthBusinessRejected) Error() string {
	return fmt.Sprintf("h5 oauth rejected: business code=%d", e.Ret)
}

// H5AuthorizationAttemptError means the authorization send was attempted.
// The response may have been lost after a one-time code was issued. Callers
// must preserve the session and must not replay on another route or account.
type H5AuthorizationAttemptError struct{ Cause error }

func (e *H5AuthorizationAttemptError) Error() string { return e.Cause.Error() }
func (e *H5AuthorizationAttemptError) Unwrap() error { return e.Cause }

// GetH5Code fetches an official-account web OAuth code for appID bound to
// redirectURI. An empty scope defaults to snsapi_base and an empty state is
// generated by oauth.Build; the returned map carries the same state so the
// caller can hand both to the script. The request runs once per call on the
// account's serialized code lock: a transport failure surfaces as-is instead
// of rebuilding sessions, because unlike wx.login there is no safe replay of
// an authorization request.
func (p *Pool) GetH5Code(ctx context.Context, loginBuffer string, request oauth.Request, accountID int64, tcpProxy string, fallbackDirect bool, expected ...*store.WechatAccount) (map[string]any, error) {
	auth, err := oauth.Build(request)
	if err != nil {
		return nil, err
	}
	codeLock := p.codeLockFor(accountID)
	if err := acquire(ctx, codeLock); err != nil {
		return nil, err
	}
	defer release(codeLock)

	st, err := p.state(ctx, loginBuffer, accountID, tcpProxy, fallbackDirect, expected...)
	if err != nil {
		return nil, err
	}
	// A dial failure may fall back before any authorization bytes are sent.
	// Pool.run also retries after a response failure; that is unsafe for H5.
	st.FallbackDirect = fallbackDirect
	result, err := p.requestH5OAuthCode(ctx, st, strings.TrimSpace(request.AppID), auth)
	if err == nil {
		p.markSessionVerified(firstAccount(expected), accountID, st)
	}
	return result, err
}

func (p *Pool) requestH5OAuthCode(ctx context.Context, st WmpfSession, appID string, auth oauth.Result) (map[string]any, error) {
	callback, err := h5OAuthRedirectRef(auth)
	if err != nil {
		return nil, err
	}
	request := buildH5OAuthRequest(auth.FullURL)
	plain := buildJSAPIPlaintext(st.Session.UIN, appID, h5OAuthURL, h5OAuthCmdID, request, st.Session.HostAppID, st.Device.SessDevice)
	envelope, err := buildTransferPacket(st.Session, plain)
	if err != nil {
		return nil, err
	}
	// Connection failures may try another target before sending, but even a
	// decrypt failure cannot prove a confirmation was not processed.
	_, reply, err := p.sendEnvelopeWithReplay(ctx, st, envelope, false)
	if err != nil {
		return nil, &H5AuthorizationAttemptError{Cause: err}
	}
	code, err := parseH5OAuthResult(reply, callback, auth.State, 0)
	if err != nil {
		return nil, &H5AuthorizationAttemptError{Cause: err}
	}
	return map[string]any{
		"code":         code,
		"appid":        appID,
		"scope":        auth.Scope,
		"state":        auth.State,
		"redirect_uri": callback,
		"mode":         "h5_oauth_auto",
	}, nil
}

// h5OAuthRedirectRef returns the redirect_uri exactly as the built authorize
// URL carries it, so the callback check compares against the string WeChat
// actually received.
func h5OAuthRedirectRef(auth oauth.Result) (string, error) {
	parsed, err := url.Parse(auth.URL)
	if err != nil {
		return "", fmt.Errorf("h5 oauth: authorize URL unparsable: %w", err)
	}
	ref := parsed.Query().Get("redirect_uri")
	if ref == "" {
		return "", errors.New("h5 oauth: authorize URL lacks redirect_uri")
	}
	return ref, nil
}

// buildH5OAuthRequest mirrors the audited oauth_authorize payload: a base
// block describing a Windows web view and the authorization URL to confirm.
func buildH5OAuthRequest(authorizeURL string) []byte {
	base := pbLen(1, nil)
	base = append(base, pbVar(2, 0)...)
	base = append(base, pbLen(3, nil)...)
	base = append(base, pbVar(4, 0)...)
	base = append(base, pbLen(5, []byte("Windows"))...)
	base = append(base, pbVar(6, 0)...)
	body := pbLen(1, base)
	body = append(body, pbLen(2, []byte(authorizeURL))...)
	body = append(body, pbLen(3, nil)...)
	return append(body, pbVar(4, 4)...)
}

// h5OAuthField is one parsed protobuf field of the reply.
type h5OAuthField struct {
	wire int
	n    uint64
	b    []byte
}

func parseH5OAuthFields(raw []byte) (map[int]h5OAuthField, error) {
	fields := map[int]h5OAuthField{}
	for offset := 0; offset < len(raw); {
		tag, next, err := readVarint(raw, offset)
		if err != nil || tag>>3 == 0 {
			return nil, errors.New("invalid protobuf tag")
		}
		offset = next
		field := h5OAuthField{wire: int(tag & 7)}
		switch field.wire {
		case 0:
			field.n, offset, err = readVarint(raw, offset)
		case 2:
			var size uint64
			size, offset, err = readVarint(raw, offset)
			if err == nil && size <= uint64(len(raw)-offset) {
				field.b = raw[offset : offset+int(size)]
				offset += int(size)
			} else {
				err = errors.New("invalid protobuf length")
			}
		default:
			err = errors.New("unsupported protobuf wire")
		}
		if err != nil {
			return nil, err
		}
		number := int(tag >> 3)
		if _, duplicate := fields[number]; duplicate {
			return nil, errors.New("duplicate protobuf field")
		}
		fields[number] = field
	}
	return fields, nil
}

// parseH5OAuthResult walks the reply for the redirect Location, requires an
// explicit zero business status next to it and validates the Location against
// the requested callback and state before returning the code.
func parseH5OAuthResult(raw []byte, callback, state string, depth int) (string, error) {
	if depth > h5OAuthMaxDepth {
		return "", errors.New("h5 oauth: response nesting limit")
	}
	fields, err := parseH5OAuthFields(raw)
	if err != nil {
		return "", err
	}
	location := ""
	if field, ok := fields[6]; ok && field.wire == 2 {
		location = string(field.b)
	}
	if strings.HasPrefix(location, "https://") || strings.HasPrefix(location, "http://") {
		ret, retErr := h5OAuthBusinessStatus(fields)
		if retErr != nil {
			return "", retErr
		}
		if ret != 0 {
			return "", &ErrH5OAuthBusinessRejected{Ret: ret}
		}
		return h5OAuthCallbackCode(location, callback, state)
	}
	if ret, retErr := h5OAuthBusinessStatus(fields); retErr == nil && ret != 0 {
		return "", &ErrH5OAuthBusinessRejected{Ret: ret}
	}
	for number := 1; number <= 32; number++ {
		field, exists := fields[number]
		if !exists || field.wire != 2 {
			continue
		}
		code, nestedErr := parseH5OAuthResult(field.b, callback, state, depth+1)
		var rejected *ErrH5OAuthBusinessRejected
		if errors.As(nestedErr, &rejected) {
			return "", rejected
		}
		if nestedErr == nil {
			return code, nil
		}
	}
	return "", errors.New("h5 oauth: callback payload absent")
}

// h5OAuthBusinessStatus reads the explicit status in field 1.1. A reply that
// carries a Location but no explicit status is rejected: only an explicit zero
// counts as success, matching the audit's "missing explicit business status".
func h5OAuthBusinessStatus(fields map[int]h5OAuthField) (int32, error) {
	base, ok := fields[1]
	if !ok || base.wire != 2 {
		return 0, errors.New("h5 oauth: missing explicit business status")
	}
	baseFields, err := parseH5OAuthFields(base.b)
	if err != nil {
		return 0, err
	}
	ret, ok := baseFields[1]
	if !ok || ret.wire != 0 {
		return 0, errors.New("h5 oauth: missing explicit business status")
	}
	return int32(ret.n), nil
}

// h5OAuthCallbackCode accepts only a Location that targets the exact callback
// (scheme, host, path, no user info, no fragment) and whose query keeps every
// callback parameter unchanged while adding exactly one code and one state.
func h5OAuthCallbackCode(location, callback, state string) (string, error) {
	got, err := url.Parse(location)
	if err != nil {
		return "", errors.New("h5 oauth: callback location unparsable")
	}
	want, err := url.Parse(callback)
	if err != nil {
		return "", errors.New("h5 oauth: callback target unparsable")
	}
	if got.Scheme != want.Scheme || got.Host != want.Host || got.Path != want.Path || got.RawPath != want.RawPath || got.User != nil || got.Fragment != "" {
		return "", errors.New("h5 oauth: callback target mismatch")
	}
	query, err := url.ParseQuery(got.RawQuery)
	if err != nil || len(query["code"]) != 1 || query.Get("code") == "" || len(query["state"]) != 1 || query.Get("state") != state {
		return "", errors.New("h5 oauth: callback code or state mismatch")
	}
	for key, values := range want.Query() {
		if key == "code" || key == "state" || len(query[key]) != len(values) || strings.Join(query[key], "\x00") != strings.Join(values, "\x00") {
			return "", errors.New("h5 oauth: callback query mismatch")
		}
	}
	return query.Get("code"), nil
}
